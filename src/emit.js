// Emitters: turn the output of resolve() into CSS, a Tailwind theme module and an Angular SCSS file.
import { valueToText } from "./resolve.js";

const HEADER = "Generated by token-sync. Do not edit by hand.";

// Top-level token groups mapped to Tailwind theme keys. Unknown groups keep their own name.
const TAILWIND_KEYS = {
  color: "colors",
  space: "spacing",
  radius: "borderRadius",
  font: "fontFamily",
  motion: "transitionDuration",
};

const cssName = (path) => `--${path.replace(/\./g, "-")}`;
const scssName = (path) => path.replace(/\./g, "-");

export function emitCss(resolved) {
  const rootLines = Object.values(resolved.tokens).map(
    (t) => `  ${cssName(t.path)}: ${valueToText(t.value)};`,
  );
  const darkLines = Object.entries(resolved.dark).map(
    ([path, value]) => `  ${cssName(path)}: ${valueToText(value)};`,
  );

  return [
    `/* ${HEADER} */`,
    `:root {`,
    ...rootLines,
    `}`,
    ``,
    `[data-theme=dark] {`,
    ...darkLines,
    `}`,
    ``,
  ].join("\n");
}

// Tailwind values point at the CSS custom properties, so the theme follows
// whichever [data-theme] is active. Include tokens.css on the page.
export function emitTailwind(resolved) {
  const theme = {};

  for (const token of Object.values(resolved.tokens)) {
    const [top, ...rest] = token.path.split(".");
    const key = TAILWIND_KEYS[top] ?? top;
    const ref = `var(${cssName(token.path)})`;

    if (rest.length === 0) {
      theme[key] = ref;
      continue;
    }
    let node = (theme[key] ??= {});
    for (const segment of rest.slice(0, -1)) {
      if (typeof node[segment] === "string") {
        throw new Error(`Token path conflict at "${token.path}"`);
      }
      node = node[segment] ??= {};
    }
    node[rest[rest.length - 1]] = ref;
  }

  return [
    `// ${HEADER}`,
    `// Usage in tailwind.config.js:`,
    `//   import { theme } from "./tailwind.tokens.js";`,
    `//   export default { theme: { extend: theme } };`,
    `export const theme = ${JSON.stringify(theme, null, 2)};`,
    ``,
    `export default theme;`,
    ``,
  ].join("\n");
}

// SCSS variables for every token ($color-brand: #1784bd;) plus maps of
// all tokens ($tokens) and of dark-mode overrides ($tokens-dark).
export function emitAngularScss(resolved) {
  const quote = (text) => `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

  const variables = Object.values(resolved.tokens).map(
    (t) => `$${scssName(t.path)}: ${valueToText(t.value)};`,
  );
  const mapEntries = (entries) =>
    entries.map(([name, value]) => `  "${name}": ${quote(valueToText(value))}`).join(",\n");

  const tokenEntries = Object.values(resolved.tokens).map((t) => [scssName(t.path), t.value]);
  const darkEntries = Object.entries(resolved.dark).map(([path, value]) => [scssName(path), value]);

  const mapBlock = (name, entries) =>
    entries.length === 0 ? `$${name}: ();` : `$${name}: (\n${mapEntries(entries)}\n);`;

  return [
    `// ${HEADER}`,
    ``,
    ...variables,
    ``,
    `// All light-mode values, keyed by variable name.`,
    mapBlock("tokens", tokenEntries),
    ``,
    `// Dark-mode overrides only, keyed by variable name.`,
    mapBlock("tokens-dark", darkEntries),
    ``,
  ].join("\n");
}
